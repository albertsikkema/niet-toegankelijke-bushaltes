// Pure SVG builder for stop markers (testable from Node.js)
function createStopSvg(compassDirection) {
  var size = 24;
  var cx = size / 2;
  var cy = size / 2;
  var r = 5;
  var chevron = '';
  if (compassDirection !== null && compassDirection !== undefined) {
    var x1 = cx - 3, y1 = cy - 8;
    var xTip = cx, yTip = cy - 11;
    var x2 = cx + 3, y2 = cy - 8;
    chevron = '<polyline points="' + x1 + ',' + y1 + ' ' + xTip + ',' + yTip + ' ' + x2 + ',' + y2 + '" ' +
      'fill="none" stroke="#d32f2f" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" ' +
      'transform="rotate(' + compassDirection + ', ' + cx + ', ' + cy + ')"/>';
  }
  return '<svg width="' + size + '" height="' + size + '" viewBox="0 0 ' + size + ' ' + size + '" xmlns="http://www.w3.org/2000/svg">' +
    chevron +
    '<circle cx="' + cx + '" cy="' + cy + '" r="' + r + '" fill="#d32f2f" stroke="#b71c1c" stroke-width="1"/>' +
    '</svg>';
}

// Marker tooltip, e.g. "Halte, Dorp — niet rolstoeltoegankelijk"
function stopMarkerTitle(stop) {
  var status = [];
  if (!stop.wheelchairAccessible) status.push('niet rolstoeltoegankelijk');
  if (!stop.visuallyAccessible) status.push('niet visueel toegankelijk');
  return stop.name + ', ' + stop.town + ' — ' + status.join(', ');
}

// [label, value] rows for the popup's description list (text rows only)
function stopPopupRows(stop, authority, concessionProviders) {
  var rows = [];
  if (stop.street) rows.push(['Straat', stop.street]);
  rows.push(['Halte', stop.code]);
  rows.push(['Wegbeheerder', authority.name]);
  var cp = stop.concessionProvider && concessionProviders && concessionProviders[stop.concessionProvider];
  if (cp && cp.name) rows.push(['Concessieverlener', cp.name]);
  return rows;
}

// GeoJSON feature that shades everything outside the boundary (the outer rings become holes)
function boundaryMaskFeature(geometry) {
  var world = [[-180, -90], [180, -90], [180, 90], [-180, 90], [-180, -90]];
  var holes = [];
  if (geometry.type === 'Polygon') {
    holes.push(geometry.coordinates[0]);
  } else if (geometry.type === 'MultiPolygon') {
    geometry.coordinates.forEach(function (polygon) { holes.push(polygon[0]); });
  }
  return { type: 'Feature', properties: {}, geometry: { type: 'Polygon', coordinates: [world].concat(holes) } };
}

// Leaflet map, markers, popups, zoom-to-authority
const MapView = (() => {
  let map;
  let clusterGroup;
  let markersByAuthority = {};
  let allMarkers = [];
  let boundaryLayer = null;
  let boundaryCache = {};
  let tileLayer = null;
  let pendingFocus = false;

  const NL_CENTER = [52.15, 5.4];
  const BOUNDARY_TYPES = ['gemeente', 'provincie', 'waterschap'];

  // CARTO API key comes from js/config.js, generated by pipeline/write-config.js
  const CARTO_KEY = (typeof window !== 'undefined' && window.APP_CONFIG && window.APP_CONFIG.cartoApiKey) || '';
  const TILE_URLS = {
    light: 'https://{s}.basemaps.cartocdn.com/rastertiles/voyager/{z}/{x}/{y}{r}.png?key=' + encodeURIComponent(CARTO_KEY),
    dark: 'https://{s}.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}{r}.png?key=' + encodeURIComponent(CARTO_KEY),
  };

  function isDarkTheme() {
    return (typeof Theme !== 'undefined') && Theme.current() === 'dark';
  }

  const POPUP_ICONS = {
    wheelchair: '<svg class="popup-icon" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="16" cy="4" r="1"/><path d="m5 8 3-3 5.5 3-2.36 3.5"/><path d="M4.24 14.5a5 5 0 0 0 6.88 6"/><path d="M13.76 17.5a5 5 0 0 0-6.88-6"/></svg>',
    visual: '<svg class="popup-icon" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M2.062 12.348a1 1 0 0 1 0-.696 10.75 10.75 0 0 1 19.876 0 1 1 0 0 1 0 .696 10.75 10.75 0 0 1-19.876 0"/><circle cx="12" cy="12" r="3"/></svg>',
  };

  function appendPopupDetail(dl, label, value, iconSvg) {
    var dt = document.createElement('dt');
    dt.className = 'popup-label';
    if (iconSvg) dt.innerHTML = iconSvg + ' ' + label; // static icon markup + fixed label
    else dt.textContent = label;
    var dd = document.createElement('dd');
    dd.className = 'popup-value';
    dd.textContent = value;
    dl.appendChild(dt);
    dl.appendChild(dd);
  }

  function createStreetViewLink(stop) {
    var link = document.createElement('a');
    link.href = 'https://www.google.com/maps/@?api=1&map_action=pano&viewpoint=' + stop.lat + ',' + stop.lon;
    link.target = '_blank';
    link.rel = 'noopener';
    link.className = 'popup-sv-link';
    link.textContent = 'Bekijk in Street View';
    return link;
  }

  // "Privaat beheer" notice, or the button that opens the email composer
  function createPopupAction(authority, concessionProviders) {
    if (authority.type === 'privaat') {
      var notice = document.createElement('p');
      notice.className = 'popup-privaat';
      notice.textContent = 'Privaat beheer';
      return notice;
    }
    var btn = document.createElement('button');
    btn.className = 'btn btn-danger popup-btn-full';
    btn.textContent = 'Email beheerder';
    btn.addEventListener('click', function () {
      Email.showModal(authority, authority.stops, concessionProviders);
    });
    return btn;
  }

  function createStopPopup(stop, authority, concessionProviders) {
    var title = stop.town + ', ' + (stop.name || stop.code);
    var div = document.createElement('div');
    div.className = 'stop-popup';
    div.setAttribute('tabindex', '-1');
    div.setAttribute('role', 'region');
    div.setAttribute('aria-label', 'Halte-informatie: ' + title);

    var h3 = document.createElement('h3');
    h3.textContent = title;
    div.appendChild(h3);

    // Details as description list for screen readers
    var dl = document.createElement('dl');
    dl.className = 'popup-details';
    stopPopupRows(stop, authority, concessionProviders).forEach(function (row) {
      appendPopupDetail(dl, row[0], row[1]);
    });
    appendPopupDetail(dl, 'Rolstoeltoegankelijk', stop.wheelchairAccessible ? 'Ja' : 'Nee', POPUP_ICONS.wheelchair);
    appendPopupDetail(dl, 'Visueel toegankelijk', stop.visuallyAccessible ? 'Ja' : 'Nee', POPUP_ICONS.visual);
    div.appendChild(dl);

    if (stop.lat && stop.lon) div.appendChild(createStreetViewLink(stop));
    div.appendChild(createPopupAction(authority, concessionProviders));
    return div;
  }

  // Mask + blue outline; returns the outline too so the caller can fit to it
  function createBoundaryLayer(geometry, isDark) {
    var mask = L.geoJSON(boundaryMaskFeature(geometry), {
      style: { stroke: false, fillColor: isDark ? '#fff' : '#000', fillOpacity: isDark ? 0.2 : 0.15 },
    });
    var border = L.geoJSON({ type: 'Feature', properties: {}, geometry: geometry }, {
      style: { color: '#1976d2', weight: 2, fill: false },
    });
    return { layer: L.layerGroup([mask, border]), border: border };
  }

  function createStopIcon(compassDirection) {
    var size = 24;
    var cx = size / 2;
    var cy = size / 2;
    return L.divIcon({
      html: createStopSvg(compassDirection),
      className: 'stop-marker',
      iconSize: [size, size],
      iconAnchor: [cx, cy],
    });
  }

  function createClusterIcon(cluster) {
    var count = cluster.getChildCount();
    var size = count < 10 ? 'small' : count < 100 ? 'medium' : 'large';
    return new L.DivIcon({
      html: '<div><span>' + count + '</span></div>',
      className: 'marker-cluster marker-cluster-' + size,
      iconSize: new L.Point(40, 40),
    });
  }

  function createStopMarker(stop, authority, ownerCode, concessionProviders) {
    var marker = L.marker([stop.lat, stop.lon], {
      icon: createStopIcon(stop.compassDirection),
      title: stopMarkerTitle(stop),
    });
    marker.bindPopup(function () {
      return createStopPopup(stop, authority, concessionProviders);
    }, { maxWidth: 300, minWidth: 260 });
    marker.stopData = stop;
    marker.authorityCode = ownerCode;
    return marker;
  }

  // Leaflet map; animations off when the user prefers reduced motion
  function createMap(animate) {
    map = L.map('map', {
      preferCanvas: true,
      center: NL_CENTER,
      zoom: 8,
      minZoom: 6,
      maxZoom: 18,
      zoomAnimation: animate,
      fadeAnimation: animate,
      markerZoomAnimation: animate,
      inertia: animate,
    });

    // Every pan (setView, fitBounds, keyboard, popup auto-pan, cluster panTo)
    // goes through panBy; make it jump when motion is reduced
    if (!animate) {
      var panBy = map.panBy;
      map.panBy = function (offset, options) {
        return panBy.call(this, offset, Object.assign({}, options, { animate: false }));
      };
    }
  }

  // Theme-aware base tiles that follow themechange events
  function addTileLayer() {
    var initialTheme = (typeof Theme !== 'undefined') ? Theme.current() : 'light';
    tileLayer = L.tileLayer(TILE_URLS[initialTheme], {
      attribution: '&copy; <a href="https://albertsikkema.com">Albert Sikkema</a> | &copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> &copy; <a href="https://carto.com/attributions">CARTO</a>',
      subdomains: 'abcd',
      maxZoom: 20,
    }).addTo(map);

    window.addEventListener('themechange', function (e) {
      tileLayer.setUrl(TILE_URLS[e.detail.theme] || TILE_URLS.light);
    });
  }

  function addMarkers(data) {
    allMarkers = [];
    for (const [ownerCode, authority] of Object.entries(data.authorities)) {
      markersByAuthority[ownerCode] = [];
      for (const stop of authority.stops) {
        if (!stop.lat || !stop.lon) continue;
        const marker = createStopMarker(stop, authority, ownerCode, data.concessionProviders);
        allMarkers.push(marker);
        markersByAuthority[ownerCode].push(marker);
      }
    }
    clusterGroup.addLayers(allMarkers);
    map.addLayer(clusterGroup);
  }

  function init(data) {
    var animate = !window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    createMap(animate);
    addTileLayer();

    clusterGroup = L.markerClusterGroup({
      animate: animate,
      chunkedLoading: true,
      maxClusterRadius: 50,
      spiderfyOnMaxZoom: true,
      showCoverageOnHover: false,
      disableClusteringAtZoom: 16,
      iconCreateFunction: createClusterIcon,
    });
    addMarkers(data);

    // Focus popup content when opened from sidebar navigation
    map.on('popupopen', function () {
      if (!pendingFocus) return;
      pendingFocus = false;
      // Small delay to ensure Leaflet has fully rendered the popup DOM
      setTimeout(function () {
        var container = document.querySelector('.stop-popup[tabindex]');
        if (container) container.focus();
      }, 50);
    });
  }

  function fitToMarkers(markers) {
    map.fitBounds(L.featureGroup(markers).getBounds().pad(0.1), { maxZoom: 14 });
  }

  function clearBoundary() {
    if (!boundaryLayer) return;
    map.removeLayer(boundaryLayer);
    boundaryLayer = null;
  }

  function showBoundary(geometry) {
    var boundary = createBoundaryLayer(geometry, isDarkTheme());
    boundaryLayer = boundary.layer.addTo(map);
    map.fitBounds(boundary.border.getBounds().pad(0.05), { maxZoom: 14 });
  }

  function fetchBoundary(ownerCode) {
    return fetch('data/boundaries/' + ownerCode + '.json')
      .then(function (res) { if (!res.ok) throw new Error(res.status); return res.json(); })
      .then(function (geometry) {
        boundaryCache[ownerCode] = geometry;
        return geometry;
      });
  }

  function zoomToAuthority(ownerCode) {
    const markers = markersByAuthority[ownerCode];
    if (!markers || markers.length === 0) return;
    fitToMarkers(markers);
  }

  function zoomToStop(stop) {
    if (!stop.lat || !stop.lon) return;

    const marker = allMarkers.find(m => m.stopData.code === stop.code);
    if (!marker) {
      map.setView([stop.lat, stop.lon], 17);
      return;
    }
    pendingFocus = true;
    // zoomToShowLayer handles unclustering and zoom, then open popup
    clusterGroup.zoomToShowLayer(marker, () => {
      map.setView([stop.lat, stop.lon], 17);
      marker.openPopup();
    });
  }

  // Show only this authority's markers, with its boundary when there is one
  function filterByAuthority(ownerCode, authType) {
    const markers = markersByAuthority[ownerCode];
    if (!markers || markers.length === 0) return;

    clusterGroup.clearLayers();
    clusterGroup.addLayers(markers);
    clearBoundary();

    if (BOUNDARY_TYPES.indexOf(authType) === -1) {
      fitToMarkers(markers);
    } else if (boundaryCache[ownerCode]) {
      showBoundary(boundaryCache[ownerCode]);
    } else {
      fetchBoundary(ownerCode)
        .then(showBoundary)
        .catch(function (err) {
          console.warn('Boundary load failed for ' + ownerCode + ':', err);
          fitToMarkers(markers);
        });
    }
  }

  function resetView() {
    clearBoundary();
    clusterGroup.clearLayers();
    clusterGroup.addLayers(allMarkers);
    map.setView(NL_CENTER, 8);
  }

  return { init, zoomToAuthority, zoomToStop, filterByAuthority, resetView };
})();

if (typeof module !== 'undefined') {
  module.exports = { createStopSvg, stopMarkerTitle, stopPopupRows, boundaryMaskFeature };
}
